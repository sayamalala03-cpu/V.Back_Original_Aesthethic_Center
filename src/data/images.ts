import type { ImageEntry, ImageFolder, ImageSubject } from '../types/image'

/**
 * THE image manifest. Pages and components refer to images by id only.
 * To replace a temporary image: export new files into public/images/<folder>/,
 * then change that one entry here. No component needs to change.
 *
 * Entries made with ph() are labeled placeholders made for this project.
 * Entries made with gen() are AI-generated concept images supplied by the project owner.
 * No stock photo, no real person and no patient result is used.
 *
 * Visual direction for the real photography:
 * Korean-inspired beauty editorial, ivory and champagne interiors, natural skin,
 * restrained gold lighting, modern equipment, minimalist compositions.
 * Keep one consistent grade across the whole site.
 */
function ph(
  id: string,
  folder: ImageFolder,
  width: number,
  height: number,
  what: string,
  subject: ImageSubject = 'scene',
  extra: Partial<ImageEntry> = {},
): ImageEntry {
  return {
    id,
    folder,
    width,
    height,
    status: 'placeholder',
    subject,
    alt: `Placeholder for ${what}`,
    fallback: `/images/${folder}/${id}.svg`,
    ...extra,
  }
}


/**
 * Concept images made with AI by the project owner, used as temporary portfolio imagery.
 * They are not photographs of real people, patients, professionals, clinics or products.
 * Every alt text must say so (checked by validateManifest). To replace one, export a new file and edit its entry.
 */
function gen(
  id: string,
  folder: ImageFolder,
  width: number,
  height: number,
  widths: readonly number[],
  alt: string,
  subject: ImageSubject = 'scene',
  extra: Partial<ImageEntry> = {},
): ImageEntry {
  const list = (ext: string) => widths.map((w) => ({ src: `/images/${folder}/${id}${w === width ? '' : `-${w}`}.${ext}`, width: w }))
  return {
    id, folder, width, height, status: 'original', subject,
    alt: `AI-generated concept image: ${alt}`,
    fallback: `/images/${folder}/${id}.jpg`,
    avif: list('avif'), webp: list('webp'), jpg: list('jpg'),
    ...extra,
  }
}

